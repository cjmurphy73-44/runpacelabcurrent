// Inventory paths and import relationships only. Never emit algorithm bodies.
import { readdir, readFile } from 'node:fs/promises';
import { join, relative, resolve, dirname, extname } from 'node:path';
const root = resolve('src');
const areas = ['science', 'math', 'utils/physiology', 'lib/algorithms'];
const files = [];
async function walk(dir) {
  for (const ent of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, ent.name);
    if (ent.isDirectory()) { if (ent.name !== '__tests__' && ent.name !== 'goldencases') await walk(p); }
    else if (/\.[jt]sx?$/.test(ent.name) && !/\.test\./.test(ent.name)) files.push(p);
  }
}
for (const area of areas) await walk(join(root, area));
files.sort();
const names = new Map();
for (const p of files) {
  const base = p.split('/').at(-1).replace(/\.[jt]sx?$/, '').toLowerCase();
  names.set(base, [...(names.get(base) || []), relative(root, p)]);
}
const duplicates = [...names.entries()].filter(([, paths]) => paths.length > 1);
const graph = new Map();
for (const p of files) {
  const code = await readFile(p, 'utf8');
  const deps = [];
  for (const [, spec] of code.matchAll(/(?:\bfrom\s*|\bimport\s*\(\s*)['"]([^'"]+)['"]/g)) {
    const dest = spec.startsWith('@/') ? resolve(root, spec.slice(2)) : spec.startsWith('.') ? resolve(dirname(p), spec) : null;
    if (dest) {
      const match = files.find(f => f === dest || f === dest + '.ts' || f === dest + '.tsx' || f === dest + '.js' || f === dest + '.jsx' || f === join(dest, 'index.ts'));
      if (match) deps.push(match);
    }
  }
  graph.set(p, deps);
}
const visited = new Set(), stack = new Set(), cycles = new Set();
function dfs(p, trail) {
  if (stack.has(p)) { cycles.add([...trail.slice(trail.indexOf(p)), p].map(x => relative(root,x)).join(' -> ')); return; }
  if (visited.has(p)) return;
  stack.add(p);
  for (const dep of graph.get(p) || []) dfs(dep, [...trail, p]);
  stack.delete(p); visited.add(p);
}
for (const p of files) dfs(p, []);
const report = [
  '# Mathematical module inventory (paths only)',
  '',
  'Generated by `node scripts/audit-math-boundaries.mjs`. A duplicate filename is a review candidate, **not proof of duplicate mathematics**. No code or coefficients are reproduced.',
  '',
  '## Inventory',
  ...areas.map(area => '- `src/' + area + '/`: ' + files.filter(p => relative(root,p).startsWith(area+'/')).length + ' implementation files'),
  '',
  '## Matching filenames requiring human review',
  ...(duplicates.length ? duplicates.map(([name, paths]) => '- `' + name + '`: ' + paths.map(p => '`src/' + p + '`').join(', ')) : ['None detected']),
  '',
  '## Internal import cycles',
  ...(cycles.size ? [...cycles].map(c => '- ' + c) : ['None detected in the audited module set']),
  '',
  '## Security classification',
  'All modules are **unclassified; treat as confidential pending owner review**. This inventory does not inspect published-science licensing, runtime reachability, or whether implementations are shipped to browsers.',
  '',
  '## Next actions',
  '1. Compare each matching-filename pair with deterministic golden-case tests before selecting an authoritative implementation.',
  '2. Trace browser bundle reachability, including transitive imports; do not publish proprietary implementations.',
  '3. Classify modules privately as published / proprietary / unknown without recording secret formulas in this report.',
  ''
].join('\n');
if (process.argv.includes('--write')) {
  const { writeFile } = await import('node:fs/promises');
  await writeFile('docs/MATH_MODULE_INVENTORY.md', report);
}
console.log(report);
